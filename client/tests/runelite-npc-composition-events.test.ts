import assert from "node:assert/strict";
import { NpcEcs } from "../game/ecs/NpcEcs";
import { PlayerEcs } from "../game/ecs/PlayerEcs";
import { baseNpcTypeId, registerNpcModelOverride } from "../custom/npcs/NpcModelOverrideRegistry";
import { bindActorEvents } from "../runelite/impl/events/actors";
import { EventBus } from "../runelite/client/eventbus/EventBus";
import { NpcChanged } from "../runelite/api/events";
const npc = new NpcEcs(4), player = new PlayerEcs(4), bus = new EventBus();
const index = npc.createNpc(50, 50, 10, 1, 64, 64, 0, 0, 0, 0);
npc.setServerMapping(index, 7);
const actor = { getId: () => baseNpcTypeId(npc.getNpcTypeId(index)) };
const client: any = { acquireNpc: () => actor, getNpcDefinition: (id: number) => ({ getId: () => id }) };
const bridge = bindActorEvents(npc, player, client, bus), previous: number[] = [];
bus.subscribe(NpcChanged, e => previous.push(e.getOld().getId()));
const synthetic = registerNpcModelOverride(10, [{ slot: 0, modelId: 42 }]);
npc.setNpcTypeId(index, synthetic); bridge.flush();
assert.deepEqual(previous, [], "model customizations do not invent an NPC composition transform");
npc.setNpcTypeId(index, 11); bridge.flush();
assert.deepEqual(previous, [10], "previous composition uses real cache ID instead of synthetic renderer ID");
bridge.dispose(); npc.setNpcTypeId(index, 12); bridge.flush(); assert.deepEqual(previous, [10]);
console.log("RuneLite NPC composition ignores renderer-only IDs and retains base previous composition");
