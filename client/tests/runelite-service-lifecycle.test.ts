import { strict as assert } from "node:assert";
import { Client } from "@runelite/api/Client";
import { GameState } from "@runelite/api/GameState";
import { WorldPoint } from "@runelite/api/coords/WorldPoint";
import { Color, Point, Rectangle, Dimension, BufferedImage, Graphics2D } from "../runelite/awt";
import { KeyEvent } from "@runelite/awt/event/KeyEvent";
import { MouseEvent } from "@runelite/awt/event/MouseEvent";
import { ConfigManager, parseConfigValue, serializeConfigValue } from "@runelite/client/config/ConfigManager";
import { RuneLiteConfig } from "@runelite/client/config/RuneLiteConfig";
import { FontType } from "@runelite/client/config/FontType";
import { PluginInjector } from "@runelite/client/plugins/PluginInjector";
import { Overlay } from "@runelite/client/ui/overlay/Overlay";
import { OverlayManager } from "@runelite/client/ui/overlay/OverlayManager";
import { OverlayInteraction } from "@runelite/client/ui/overlay/OverlayInteraction";
import { OverlayPosition } from "@runelite/client/ui/overlay/OverlayPosition";
import { OverlayLayer } from "@runelite/client/ui/overlay/OverlayLayer";
import { TooltipManager } from "@runelite/client/ui/overlay/tooltip/TooltipManager";
import { ClientThread } from "@runelite/client/callback/ClientThread";
import { KeyManager } from "@runelite/client/input/KeyManager";
import { ChatboxPanelManager } from "@runelite/client/game/chatbox/ChatboxPanelManager";
import { FpsPlugin } from "@runelite/client/plugins/fps/FpsPlugin";
import { FpsConfig } from "@runelite/client/plugins/fps/FpsConfig";
import { DrawManager } from "@runelite/client/ui/DrawManager";
import { WorldMapPoint } from "@runelite/client/ui/overlay/worldmap/WorldMapPoint";
import { WorldMapPointManager } from "@runelite/client/ui/overlay/worldmap/WorldMapPointManager";
import { WorldMapOverlay } from "@runelite/client/ui/overlay/worldmap/WorldMapOverlay";
import { ScheduledExecutorService, CancellationException } from "@runelite/client/util/ScheduledExecutorService";
import type { WorldView } from "@runelite/api/WorldView";
import { WorldViewManager } from "../game/worldview/WorldViewManager";
import type { DrawCallbacks } from "@runelite/api/hooks/DrawCallbacks";
import { DrawCallbackDispatcher, bindDrawCallbackLifecycle } from "../runelite/impl/DrawCallbackDispatcher";
import { Text } from "@runelite/client/util/Text";
import { ColorUtil } from "@runelite/client/util/ColorUtil";
import { ChatMessageBuilder } from "@runelite/client/chat/ChatMessageBuilder";
async function run() {
    assert.equal(Text.escapeJagex("<hello>@\n"), "<lt>hello<gt><at><br>");
    assert.equal(Text.unescapeJagex("<col=ffffff>hello<lt><br><at></col>"), "hello<\n@");
    assert.equal(Text.toJagexName("ÉName_-\u00a0other"), "Name   other");
    assert.equal(Text.matchesSearchTerms(["quest", "helper"], ["questhelper"]), true);
    assert.equal(Text.matchesSearchTerms(["questhelper"], ["questhelpr"]), true, "upstream fuzzy keyword match");
    assert.equal(ColorUtil.toHexColor(Color.RED), "#ff0000");
    assert.equal(ColorUtil.colorTag(Color.RED), "<col=ff0000>");
    assert.equal(new ChatMessageBuilder().append("<hello>@").build(), "<lt>hello<gt><at>");
    const fontItem = RuneLiteConfig.items.dynamicOverlayFont;
    const custom = FontType.REGULAR.withSize(18).withItalic(true);
    const encoded = serializeConfigValue(fontItem, custom), decoded = parseConfigValue(fontItem, encoded) as FontType;
    assert.equal(decoded.getFont().getSize(), 18);
    assert.equal(decoded.isItalic(), true);
    assert.equal(parseConfigValue(fontItem, "SMALL"), FontType.SMALL);
    assert.equal(parseConfigValue(fontItem, '{"family":"x","size":-20,"bold":false,"italic":false}'), fontItem.default, "invalid font is rejected at config boundary");
    const config = new ConfigManager(), manager = new OverlayManager(config);
    class Movable extends Overlay {
        constructor() { super(); }
        render(): Dimension { return new Dimension(60, 40); }
    }
    const box = new Movable();
    box.setBounds(new Rectangle(100, 100, 60, 40));
    manager.add(box);
    const frame = { canvas: new Rectangle(0, 0, 500, 400), viewport: new Rectangle(20, 20, 400, 300) };
    const interaction = new OverlayInteraction(manager, () => frame);
    const mouse = (x: number, y: number, button = 0, altKey = true) => new MouseEvent({ button, altKey, preventDefault() { } } as globalThis.MouseEvent, x, y);
    interaction.mousePressed(mouse(110, 110));
    interaction.mouseDragged(mouse(160, 180));
    interaction.mouseReleased(mouse(160, 180));
    assert.deepEqual(box.getPreferredLocation(), new Point(150, 170));
    assert.equal(manager.getLayer(OverlayLayer.ABOVE_WIDGETS).includes(box), true, "detached overlay moves above widgets");
    const restored = new Movable();
    new OverlayManager(config).add(restored);
    assert.deepEqual(restored.getPreferredLocation(), new Point(150, 170));
    assert.equal(config.getConfiguration("runelite", "Movable_preferredLocation"), "150:170");
    box.setResizable(true);
    box.setBounds(new Rectangle(100, 100, 60, 40));
    interaction.mousePressed(mouse(159, 139));
    interaction.mouseDragged(mouse(199, 169));
    interaction.mouseReleased(mouse(199, 169));
    assert.deepEqual(box.getPreferredSize(), new Dimension(100, 70));
    interaction.mousePressed(mouse(120, 120));
    interaction.mouseDragged(mouse(25, 25));
    interaction.mouseReleased(mouse(25, 25));
    assert.equal(box.getPreferredPosition(), null, "return to default corner clears override");
    assert.equal(box.getPreferredLocation(), null);
    box.setPosition(OverlayPosition.DYNAMIC);
    assert.equal(box.isMovable(), false);
    assert.equal(box.isSnappable(), false);
    box.setPosition(OverlayPosition.DETACHED);
    assert.equal(box.isMovable(), true);
    assert.equal(box.isSnappable(), false);
    manager.resetOverlay(box);
    assert.equal(config.getConfiguration("runelite", "Movable_preferredSize"), undefined);
    const client = { getGameState: () => GameState.LOGGED_IN } as Client, keys = new KeyManager(client), thread = new ClientThread();
    let buffer = "", closed = 0, finished = "";
    const panel = new ChatboxPanelManager(thread, keys, { open(value) { buffer = value; }, update(value) { buffer = value; }, close() { closed++; }, isAvailable: () => true });
    panel.openTextInput("Name").value("ab").onDone(value => { finished = value; }).build();
    thread.runClientTick(() => { });
    const key = (code: number, value: string) => new KeyEvent({ keyCode: code, key: value, type: "keydown", preventDefault() { } } as KeyboardEvent);
    keys.processKeyPressed(key(67, "c"));
    assert.equal(buffer, "abc");
    keys.processKeyPressed(key(8, "Backspace"));
    assert.equal(buffer, "ab");
    keys.processKeyPressed(key(13, "Enter"));
    assert.equal(finished, "ab");
    assert.equal(panel.getCurrentInput(), null);
    assert.equal(closed, 1);
    panel.openTextInput("Again").build();
    thread.runClientTick(() => { });
    panel.onGameStateChanged({ getGameState: () => GameState.LOGIN_SCREEN });
    assert.equal(closed, 2, "logout releases keyboard and closes plugin input");
    const limits: (number | null)[] = [], draws = new DrawManager(() => ({ width: 500, height: 400 }) as HTMLCanvasElement, value => limits.push(value));
    const injector = new PluginInjector(config).provide(Client, client).provide(OverlayManager, manager).provide(DrawManager, draws);
    const fps = injector.runWith(() => new FpsPlugin());
    assert.equal(fps.isEnabled(), false);
    await fps.start();
    assert.equal(limits.at(-1), null);
    assert.ok(manager.anyMatch(overlay => overlay.constructor.name === "FpsOverlay"));
    config.setConfiguration("fpscontrol", "limitFps", true);
    config.setConfiguration("fpscontrol", "maxFps", 30);
    fps.onConfigChanged({ getGroup: () => "fpscontrol" });
    assert.equal(limits.at(-1), 30);
    config.setConfiguration("fpscontrol", "limitFpsUnfocused", true);
    config.setConfiguration("fpscontrol", "maxFpsUnfocused", 15);
    fps.onFocusChanged({ isFocused: () => false });
    assert.equal(limits.at(-1), 15);
    await fps.stop();
    assert.equal(limits.at(-1), null);
    assert.equal(manager.anyMatch(overlay => overlay.constructor.name === "FpsOverlay"), false);
    assert.equal(config.getConfig(FpsConfig).drawFps(), true);
    const image = new BufferedImage({ width: 10, height: 10 } as HTMLCanvasElement), point = new WorldMapPoint(new WorldPoint(3200, 3200, 0), image);
    point.setSnapToEdge(true);
    point.setJumpOnClick(true);
    point.setTooltip("Map target");
    const worldPoints = new WorldMapPointManager();
    worldPoints.add(point);
    const tooltips = new TooltipManager();
    let jumps = 0, snaps = 0;
    point.onEdgeSnap = () => { snaps++; };
    const worldOverlay = new WorldMapOverlay(worldPoints, () => ({ bounds: new Rectangle(0, 0, 100, 100), mouse: new Point(95, 50), project: () => new Point(200, 50), jump: () => { jumps++; } }), tooltips);
    const context = new Proxy({}, { get: (_target, name) => name === "getTransform" ? () => ({ a: 1, b: 0, c: 0, d: 1, e: 0, f: 0 }) : () => { } }) as CanvasRenderingContext2D;
    const graphics = new Graphics2D(context);
    worldOverlay.render(graphics);
    assert.equal(snaps, 1);
    assert.equal(point.isCurrentlyEdgeSnapped(), true);
    assert.equal(tooltips.getTooltips().length, 1);
    worldOverlay.mousePressed(mouse(95, 50, 0, false));
    assert.equal(jumps, 1);
    graphics.dispose();
    const drawCalls: unknown[][] = [];
    const drawClient = { getCameraFpX: () => 10, getCameraFpY: () => 20, getCameraFpZ: () => -30, getCameraFpPitch: () => .25, getCameraFpYaw: () => .5, getPlane: () => 1 } as Client;
    const dispatcher = new DrawCallbackDispatcher(drawClient), callback = { draw(...args: unknown[]) { drawCalls.push(["frame", ...args]); }, drawScene(...args: unknown[]) { drawCalls.push(["scene", ...args]); }, postDrawScene() { drawCalls.push(["post"]); }, despawnWorldView(view: WorldView) { drawCalls.push(["despawn", view]); } } satisfies DrawCallbacks;
    dispatcher.setDrawCallbacks(callback);
    dispatcher.beforeScene();
    dispatcher.afterScene();
    dispatcher.afterFrame(0xff0000);
    assert.deepEqual(drawCalls, [["scene", 10, 20, -30, .25, .5, 1], ["post"], ["frame", 0xff0000]]);
    assert.throws(() => dispatcher.setDrawCallbacks({ ...callback, drawPass() { } }), /native rasterizer replacement/);
    for (const method of ["loadScene", "swapScene", "loadWorldView"])
        assert.throws(() => dispatcher.setDrawCallbacks({ ...callback, [method]() { } }), /atomic native scene loading/);
    assert.equal(dispatcher.getDrawCallbacks(), callback, "rejected renderer overrides leave previous callbacks intact");
    const views = new WorldViewManager(), wrappers = new Map<number, WorldView>();
    const child = views.createWorldView(7, 8, 8), wrapper = { getId: () => 7 } as WorldView;
    wrappers.set(7, wrapper);
    const disposeDrawLifecycle = bindDrawCallbackLifecycle(views, { getWorldView(id: number) { assert.equal(views.getWorldView(id), child, "despawn is posted before native removal"); return wrappers.get(id) ?? null; } } as Client, dispatcher);
    views.removeWorldView(7);
    assert.deepEqual(drawCalls[3], ["despawn", wrapper]);
    disposeDrawLifecycle();
    assert.equal(views.viewUnloadedListeners.size, 0);
    dispatcher.setDrawCallbacks(null);
    dispatcher.afterFrame(0);
    assert.equal(drawCalls.length, 4);
    const scheduler = new ScheduledExecutorService();
    const canceled = scheduler.schedule(() => 99, 1000, "MILLISECONDS");
    assert.equal(canceled.cancel(), true);
    assert.equal(canceled.cancel(), false);
    assert.equal(canceled.isDone(), true);
    assert.equal(canceled.isCancelled(), true);
    await assert.rejects(canceled.get(), CancellationException);
    assert.equal(await scheduler.submit(() => 42).get(), 42);
    const failure = scheduler.submit(() => { throw new Error("task failed"); });
    await assert.rejects(failure.get(), /task failed/);
    let repetitions = 0;
    const repeat = scheduler.scheduleAtFixedRate(() => { repetitions++; }, 0, 2, "MILLISECONDS");
    await new Promise(resolve => setTimeout(resolve, 12));
    assert.ok(repetitions >= 1);
    repeat.cancel();
    const count = repetitions;
    await new Promise(resolve => setTimeout(resolve, 5));
    assert.equal(repetitions, count);
    const pending = scheduler.schedule(() => 7, 2, "MILLISECONDS");
    scheduler.shutdown();
    assert.equal(await pending.get(), 7, "graceful shutdown permits already scheduled one-shot tasks");
    assert.throws(() => scheduler.submit(() => 0), /shut down/);
    const forced = new ScheduledExecutorService(), aborted = forced.schedule(() => 1, 1000, "MILLISECONDS");
    forced.shutdownNow();
    await assert.rejects(aborted.get(), CancellationException);
    console.log("RuneLite font config, overlay editing, chatbox, FPS, world map and executor lifecycle tests passed");
}
run().catch(error => { console.error(error); process.exitCode = 1; });
