import assert from "node:assert/strict";
import type { Client } from "../runelite/api/Client";
import { MenuAction } from "../runelite/api/MenuAction";
import { EventBus } from "../runelite/client/eventbus/EventBus";
import { MenuImpl } from "../runelite/impl/MenuImpl";
import { bindMenuEvents } from "../runelite/impl/MenuEventAdapter";
import { MenuEntryAdded } from "../runelite/api/events/MenuEntryAdded";
import { MenuOpened } from "../runelite/api/events/MenuOpened";
import { MenuOptionClicked } from "../runelite/api/events/MenuOptionClicked";
import { PostMenuSort } from "../runelite/api/events/PostMenuSort";
import { applyMenuTransform } from "../ui/menu/menuTransforms";
import { openPluginMenu, dispatchMenuAction } from "../ui/menu/menuEvents";
import { MenuState, MenuOpcode } from "../ui/menu/MenuState";
import { MenuTargetType } from "../rs/MenuEntry";
import { worldEntriesToSimple } from "../ui/menu/MenuBridge";
import { ClientUiService } from "../runelite/impl/ClientUiService";
import { ClientState } from "../game/ClientState";
const npc = { getIndex: () => 12 };
const child = { getItemId: () => 4151 };
const widget = { getItemId: () => -1, getChild: (index: number) => index === 3 ? child : null };
const client = { getNpcs: () => [npc], getPlayers: () => [], getWidget: () => widget } as unknown as Client;
const menu = new MenuImpl(client);
const bus = new EventBus();
const dispose = bindMenuEvents(client, menu, bus);
let added = 0, sorted = 0, clicks = 0;
const unadded = bus.subscribe(MenuEntryAdded, (event) => {
    added++;
    if (event.getOption() === "Talk-to") event.getMenuEntry().setTarget("Changed target").setForceLeftClick(true);
});
const unsorted = bus.subscribe(PostMenuSort, () => sorted++);
const state = new MenuState();
let sideEffects = 0;
const rows = worldEntriesToSimple([{ option: "Talk-to", targetId: 100, targetType: MenuTargetType.NPC,
    npcServerId: 12, targetName: "NPC", targetLevel: 1, mapX: 1, mapY: 2, actionIndex: 0, onClick: () => sideEffects++ }], { menuState: state });
assert.equal(added, 1); assert.equal(sorted, 1);
const entry = menu.getMenuEntries()[0];
assert.equal(entry.getNpc(), npc); assert.equal(entry.getType(), MenuAction.NPC_FIRST_OPTION);
assert.equal(rows[0].target, "Changed target"); assert.equal(rows[0].forceLeftClick, true);
assert.equal(menu.getMenuEntries()[0], entry, "stable entry identity during an open menu");
const unclick = bus.subscribe(MenuOptionClicked, (event) => { clicks++; event.consume(); });
let closed = 0;
state.invoke(rows[0].menuStateIndex!, 1, 2, { closeMenu: () => closed++ });
assert.equal(clicks, 1); assert.equal(sideEffects, 0, "consumed click must stop native/local dispatch"); assert.equal(closed, 1);
const unopen = bus.subscribe(MenuOpened, (event) => {
    const first = event.getFirstEntry()!;
    assert.equal(first, entry);
    event.setMenuEntries([]);
});
assert.deepEqual(openPluginMenu(rows), []);
unopen(); unclick(); unadded(); unsorted();
menu.setDisplayEntries(rows);
let callback = 0;
const custom = menu.createMenuEntry(-1).setOption("Plugin option").onClick(() => callback++);
const action = { param0: 0, param1: 0, opcode: MenuAction.RUNELITE.getId(), identifier: 0,
    itemId: -1, option: "Plugin option", target: "", screenX: 1, screenY: 2 };
let native = 0;
dispatchMenuAction(action, () => native++);
assert.equal(callback, 1); assert.equal(native, 0, "RuneLite callback entry must not send a game packet");
assert.equal(menu.getMenuEntries().at(-1), custom);
assert.throws(() => menu.createMenuEntry(99), RangeError);
const sub = custom.createSubMenu(); sub.createMenuEntry(-1).setOption("Child");
assert.equal(custom.getSubMenu()!.getMenuEntries()[0].getOption(), "Child");
assert.equal(menu.toDisplayEntries()[0].subEntries![0].option, "Child");
custom.deleteSubMenu(); assert.equal(custom.getSubMenu(), null);
const widgetRows = applyMenuTransform([{ option: "Wield", opcode: MenuOpcode.CC_OP }],
    { surface: "widget", menu: false, widgetId: 149 << 16, childIndex: 3, itemId: 4151 });
assert.equal(widgetRows[0].param0, 3); assert.equal(widgetRows[0].param1, 149 << 16);
assert.equal(widgetRows[0].identifier, 1, "an implicit widget operation is op one in plugin metadata too");
const itemEntry = menu.getMenuEntries()[0];
assert.equal(itemEntry.getWidget(), child);
for (const [identifier, operation] of [[2,1], [3,2], [4,3], [6,4], [7,5], [5,-1], [10,-1]]) {
    itemEntry.setIdentifier(identifier);
    assert.equal(itemEntry.getItemOp(), operation);
}
itemEntry.setParam0(4);
assert.equal(itemEntry.getWidget(), null, "missing dynamic children must not resolve to parent");
const ui = new ClientUiService({} as any, client as any);
ClientState.isSpellSelected = true;
ClientState.selectedSpellChildIndex = 3;
assert.equal(ui.getSelectedWidget(), child);
ClientState.selectedSpellChildIndex = 4;
assert.equal(ui.getSelectedWidget(), null);
ClientState.selectedSpellChildIndex = -1;
assert.equal(ui.getSelectedWidget(), widget);
ClientState.isSpellSelected = false;
let nested = 0;
const unnest = bus.subscribe(MenuOptionClicked, () => { nested++; });
dispatchMenuAction({ ...action, opcode: MenuOpcode.Cancel, option: "Cancel" }, (data) => dispatchMenuAction(data, () => native++));
assert.equal(nested, 1, "nested dispatch describes the same click");
unnest(); dispose();
console.log("RuneLite menu API: identity, mutations, open replacement, consumed clicks, plugin callbacks and submenus passed");
