import assert from "node:assert/strict";
import { EventBus } from "../runelite/client/eventbus/EventBus";
import { GameTick } from "../runelite/api/events/GameTick";
import { CallbacksImpl } from "../runelite/impl/CallbacksImpl";
import { KeyManager } from "../runelite/client/input/KeyManager";
import { MouseManager } from "../runelite/client/input/MouseManager";
import { MouseEvent } from "../runelite/awt/event/MouseEvent";
import { KeyEvent } from "../runelite/awt/event/KeyEvent";
import { GameState } from "../runelite/api/GameState";
import { SpritePixels as NativeSprite } from "../rs/sprite/SpritePixels";
import { SpritePixelsImpl } from "../runelite/impl/SpritePixelsImpl";
const bus = new EventBus(), mouse = new MouseManager(), keys = new KeyManager({ getGameState: () => GameState.LOGGED_IN } as any);
const lifecycle: string[] = [];
const callbacks = new CallbacksImpl(bus, mouse, keys, { tick: () => lifecycle.push("tick"), tickEnd: () => lifecycle.push("end"), frame: () => lifecycle.push("frame"), serverTick: () => lifecycle.push("server"), openUrl: url => lifecycle.push(url), isOutdated: () => false });
let count = 0;
bus.subscribe(GameTick, () => { count++; if (count === 1) callbacks.postDeferred(new GameTick()); });
callbacks.postDeferred(new GameTick()); assert.equal(count, 0);
callbacks.flushDeferred(); assert.equal(count, 1, "deferred work created during dispatch stays queued");
callbacks.flushDeferred(); assert.equal(count, 2);
callbacks.tick(); callbacks.tickEnd(); callbacks.frame(); callbacks.serverTick(); callbacks.openUrl("https://runelite.net");
assert.deepEqual(lifecycle, ["tick", "end", "frame", "server", "https://runelite.net"]);
const raw = { ctrlKey: false, shiftKey: false, altKey: false, metaKey: false, button: 0, detail: 1, preventDefault() {} } as unknown as globalThis.MouseEvent;
mouse.registerMouseListener({ mousePressed(event) { event.consume(); return event; } });
assert.equal(callbacks.mousePressed(new MouseEvent(raw, 10, 20)).isConsumed(), true, "callback uses native input interception manager");
keys.registerKeyListener({ keyPressed(event) { event.consume(); } });
const key = new KeyEvent({ key: "a", code: "KeyA", ctrlKey: false, shiftKey: false, altKey: false, metaKey: false, preventDefault() {} } as KeyboardEvent);
callbacks.keyPressed(key); assert.equal(key.isConsumed(), true);
const sprite = new SpritePixelsImpl(NativeSprite.fromPixels(Int32Array.from([0, 0xff0000]), 2, 1));
assert.deepEqual([...sprite.getPixels()], [0, 0xff0000], "RuneLite raw sprite pixels retain RGB transparency sentinel");
sprite.setOffsetX(4); assert.equal(sprite.getOffsetX(), 4);
callbacks.dispose();
console.log("RuneLite callbacks, deferred cycle ordering, input consumption and sprite pixels passed");
