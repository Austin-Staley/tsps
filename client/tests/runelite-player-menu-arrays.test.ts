import assert from "node:assert/strict";
import { ClientState } from "../game/ClientState";
import { PlayerMenuArrays } from "../runelite/impl/PlayerMenuArrays";
import { MenuAction } from "../runelite/api/MenuAction";
const menus = new PlayerMenuArrays();
ClientState.playerOptions.clear();
assert.deepEqual(menus.options, Array(8).fill(null));
ClientState.playerOptions.set(1, { option: "Attack", priority: true });
assert.equal(menus.options[0], "Attack");
assert.equal(menus.priorities[0], false, "native priority means not deprioritized");
let changed = -1;
const listener = (index: number) => { changed = index; };
ClientState.playerOptionsChangedListeners.add(listener);
menus.options[4] = "Mark";
menus.priorities[4] = true;
menus.types[4] = MenuAction.RUNELITE_PLAYER.getId();
assert.deepEqual(ClientState.playerOptions.get(5), {option:"Mark",priority:false,opcode:1503});
assert.equal(changed, 4);
assert.equal(menus.types[4], 1503);
menus.options[4] = null;
assert.equal(ClientState.playerOptions.get(5)!.option, "");
assert.equal(menus.options[4], null);
assert.throws(() => { menus.options[8] = "Out of bounds"; }, RangeError);
ClientState.playerOptions.clear();
assert.deepEqual(menus.options, Array(8).fill(null), "retained array observes native reset");
ClientState.playerOptionsChangedListeners.delete(listener);
console.log("RuneLite player arrays: live packet reads, writable options/priorities/opcodes, reset and indexing passed");
