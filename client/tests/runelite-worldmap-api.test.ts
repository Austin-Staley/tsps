import { strict as assert } from "node:assert";
import { WorldMapState, WorldMapArea } from "../rs/map/WorldMapArea";
import { WorldMapApi } from "../runelite/impl/WorldMapApi";
import { WorldPoint } from "@runelite/api/coords/WorldPoint";
import { Point } from "@runelite/awt/Point";
import type { SpritePixels } from "@runelite/api/SpritePixels";
import type { MapElementType } from "../rs/config/meltype/MapElementType";
function makeArea(id: number, mapX: number, mapY: number): WorldMapArea {
    const area = new WorldMapArea();
    area.id = id;
    area.regionLowX = area.regionHighX = mapX;
    area.regionLowY = area.regionHighY = mapY;
    area.origin = { plane: 0, x: mapX * 64, y: mapY * 64 };
    area.zoom = 100;
    area.sections.push({ containsPosition: (x, y) => x >= mapX * 64 && x < (mapX + 1) * 64 && y >= mapY * 64 && y < (mapY + 1) * 64, containsCoord: (plane, x, y) => plane === 0 && x >= mapX * 64 && x < (mapX + 1) * 64 && y >= mapY * 64 && y < (mapY + 1) * 64, position: (_plane, x, y) => ({ x, y }), coord: (x, y) => ({ plane: 0, x, y }), expandBounds: () => { } });
    return area;
}
const state = WorldMapState.empty(), first = makeArea(10, 50, 50), second = makeArea(20, 60, 60);
state.areasById.set(first.id, first);
state.areasById.set(second.id, second);
let invalidations = 0, sprites = 0;
const sprite = { getWidth: () => 10 } as SpritePixels;
const elements = new Map<number, MapElementType>([[42, { category: 7, spriteId: 123, worldMapVisible: true } as MapElementType], [43, { category: 8, spriteId: -1, worldMapVisible: true } as MapElementType]]);
const api = new WorldMapApi({ getState: () => state, getElement: id => elements.get(id)!, getSprite: id => { assert.equal(id, 123); sprites++; return sprite; }, invalidate: () => { invalidations++; } });
assert.equal(api.getWorldMapData(), null);
assert.equal(api.getWorldMapRenderer(), null);
state.setCurrentMapAreaId(first.id);
assert.deepEqual(api.getWorldMapPosition(), new Point(3200, 3200));
assert.equal(api.getWorldMapZoom(), 4);
state.setZoomPercentage(50);
assert.equal(api.getWorldMapZoom(), 2);
api.setWorldMapPositionTarget(new WorldPoint(3205, 3206, 0));
assert.equal(state.targetX, 3205);
assert.equal(state.targetY, 3206);
assert.equal(invalidations, 1);
const data = api.getWorldMapData()!;
assert.equal(data.surfaceContainsPosition(3201, 3201), true);
assert.equal(data.surfaceContainsPosition(5000, 5000), false);
const renderer = api.getWorldMapRenderer()!;
assert.equal(renderer.isLoaded(), state.isLoaded());
assert.equal(api.getWorldMapRenderer(), renderer);
const regions = renderer.getMapRegions();
assert.equal(regions.length, 1);
assert.equal(regions[0].length, 1);
state.setTileIcons(50, 50, 0, [{ localX: 3, localY: 4, elementId: 42, category: 7, spriteId: 123, sourceX: 3203, sourceY: 3204 }]);
let icons = regions[0][0].getMapIcons();
assert.equal(icons.length, 1);
assert.equal(icons[0].getType(), 42);
assert.deepEqual(icons[0].getCoordinate(), new WorldPoint(3203, 3204, 0));
state.setCategoryEnabled(7, false);
assert.equal(regions[0][0].getMapIcons().length, 0);
state.setCategoryEnabled(7, true);
state.setElementEnabled(42, false);
assert.equal(regions[0][0].getMapIcons().length, 0);
state.setElementEnabled(42, true);
const config = api.getMapElementConfig(42);
assert.equal(config.getCategory(), 7);
assert.equal(config.getMapIcon(false), sprite);
assert.equal(sprites, 1);
assert.equal(api.getMapElementConfig(42), config);
assert.equal(api.getMapElementConfig(43).getMapIcon(false), null);
state.setCurrentMapAreaId(second.id);
assert.notEqual(api.getWorldMapRenderer(), renderer, "native area change recreates world-map renderer");
assert.equal(regions[0][0].getMapIcons().length, 1, "old region retains its area's metadata rather than reading the new area");
assert.equal(api.getWorldMapRenderer()!.getMapRegions()[0][0].getMapIcons().length, 0);
const current = api.getWorldMapData()!, before = api.getWorldMapRenderer();
api.initializeWorldMap(current);
assert.notEqual(api.getWorldMapRenderer(), before);
assert.equal(state.displayX, 3840);
assert.throws(() => api.initializeWorldMap({ surfaceContainsPosition: () => true }), /loaded cache/);
console.log("RuneLite native world-map position, zoom, targeting, regions, icons and area lifecycle tests passed");
